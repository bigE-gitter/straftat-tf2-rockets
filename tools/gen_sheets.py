"""Generate StraftatRockets/Sheets.g.cs from sheets/tf2_values.json and sheets/tuning.json (each row -> one constant)."""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
rows = json.load(open(os.path.join(ROOT, "sheets", "tf2_values.json"), encoding="utf-8"))["rows"]
lines = ["// GENERATED by straftat_mod/tools/gen_sheets.py from sheets/tf2_values.json and sheets/tuning.json - edit the sheets, not this file.",
         "namespace StraftatRockets", "{", "    internal static class Tf2", "    {"]
for r in rows:
    lines.append(f"        /// <summary>{r['source']} (TF2 {r['tf2_value']} {r['tf2_unit']})</summary>")
    lines.append(f"        public const float {r['id']} = {float(r['straftat_value'])!r}f; // {r['straftat_unit']}")
lines += ["    }", "", "    internal static class Tuning", "    {"]
for r in json.load(open(os.path.join(ROOT, "sheets", "tuning.json"), encoding="utf-8"))["rows"]:
    lines.append(f"        /// <summary>{r['why']}</summary>")
    lines.append(f"        public const float {r['id']} = {float(r['value'])!r}f; // {r['unit']}")
lines += ["    }", "}"]
out = os.path.join(ROOT, "StraftatRockets", "Sheets.g.cs")
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w", newline="\n", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote", out)

# sheets/models.json -> StraftatRockets/Models.g.cs: what the plugin loads from the player's own TF2 at startup
models = json.load(open(os.path.join(ROOT, "sheets", "models.json"), encoding="utf-8"))["rows"]
def cs(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'
def arr(a):
    return "new string[] { " + ", ".join(cs(x) for x in a) + " }" if a else "new string[0]"
ml = ["// GENERATED by straftat_mod/tools/gen_sheets.py from sheets/models.json - edit the sheet, not this file.",
      "namespace StraftatRockets", "{", "    internal static class ModelSheet", "    {",
      "        internal struct Row", "        {",
      "            public string Id, Name, Kind, Mdl, Prefab;", "            public string[] Extra, FireWaves, ExplodeWaves;", "        }", "",
      "        internal static readonly Row[] Rows =", "        {"]
for r in models:
    ml.append(f"            new Row {{ Id = {cs(r['id'])}, Name = {cs(r['name'])}, Kind = {cs(r['kind'])}, Mdl = {cs(r['mdl'])}, Prefab = {cs(r.get('prefab', ''))}, "
              f"Extra = {arr(r.get('extra', []))}, FireWaves = {arr(r.get('fire_waves', []))}, ExplodeWaves = {arr(r.get('explode_waves', []))} }},")
ml += ["        };", "    }", "}"]
out2 = os.path.join(ROOT, "StraftatRockets", "Models.g.cs")
open(out2, "w", newline="\n", encoding="utf-8").write("\n".join(ml) + "\n")
print("wrote", out2)
